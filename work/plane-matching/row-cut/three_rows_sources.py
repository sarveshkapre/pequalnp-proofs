"""Find disjoint comparisons forcing distinct projected input wires."""
from argparse import ArgumentParser
from itertools import combinations
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "grid/search"))
from cases import BANK, ROWS, allowed


def bits(mask):
    return [1 << i for i in range(mask.bit_length()) if mask & (1 << i)]


def comparisons(rows):
    active = ROWS[rows[0]] | ROWS[rows[1]] | ROWS[rows[2]]
    sources = set(bits(active)) | {m & active for m in BANK}
    for r, mask in enumerate(ROWS):
        if r not in rows:
            sources.update(m for m in range(active+1) if m & active & mask == m)
    sources = sorted(sources - {0})
    witnesses = {}
    for r in rows:
        for line in bits(ROWS[r]):
            for negative in range(active+1):
                if negative & active != negative or not allowed(1 << r, negative):
                    continue
                possible = sum(1 << i for i, m in enumerate(sources)
                               if m & line and not m & negative)
                witnesses.setdefault(possible, (r, line.bit_length()-1, negative))
    return sources, witnesses


def packing(sets, length):
    if length == 0:
        return []
    for i, candidate in enumerate(sets):
        if len(sets) - i < length:
            break
        tail = packing([s for s in sets[i+1:] if not s & candidate], length-1)
        if tail is not None:
            return [candidate, *tail]
    return None


def certificates(rows):
    sources, witnesses = comparisons(rows)
    shared = sum(l for l in bits(2047) if sum(bool(l & ROWS[r]) for r in rows) >= 2)
    row_bits = sum(1 << r for r in rows)
    for missing in ([s for s in sources if s.bit_count() == 1]
                    if shared.bit_count() == 1 else [0]):
        wanted = 12 if missing else 6
        filtered = {}
        for possible, witness in witnesses.items():
            if missing:
                possible &= ~(1 << sources.index(missing))
            elif any(possible >> i & 1 and src & shared for i, src in enumerate(sources)):
                continue
            filtered.setdefault(possible, witness)
        if 0 in filtered:
            selected = [0]
        else:
            minimal = []
            for s in sorted(filtered, key=lambda m: (m.bit_count(), m)):
                if all(t & s != t for t in minimal):
                    minimal.append(s)
            selected = packing(minimal, wanted)
            assert selected is not None
        yield row_bits, missing, [filtered[k] for k in selected]


def lean_data():
    lines = []
    for rows in combinations(range(6), 3):
        for rs, missing, witnesses in certificates(rows):
            ws = ", ".join(f"({r},{l},{n})" for r,l,n in witnesses)
            lines.append(f"  ({rs}, {missing}, [{ws}])")
    return ("-- Generated by three_rows_sources.py; checked against the physical inputs.\n"
            "def gridSourceData : List (Nat × Nat × List (Nat × Nat × Nat)) := [\n"
            + ",\n".join(lines) + "]\n")


if __name__ == "__main__":
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    path = Path(__file__).with_name("ThreeRowData.lean")
    data = lean_data()
    if parser.parse_args().write:
        path.write_text(data)
    else:
        assert path.read_text() == data
        print("All 38 comparison families reproduced.")
